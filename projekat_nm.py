velicina_prozora = 80
korak = 40

def napravi_sekvence(podaci, velicina_prozora, korak):
    X = []
    y = []

    grupe = podaci.groupby(['user', 'activity'])

    for (_, _), grupa in grupe:
        grupa = grupa.sort_values('timestamp')

        ulaz = grupa[['x', 'y', 'z']].values
        izlaz = grupa['aktivnost_id'].values

        if len(grupa) < velicina_prozora:
            continue

        for pocetak in range(0, len(grupa) - velicina_prozora + 1, korak):
            kraj = pocetak + velicina_prozora

            prozor_ulaz = ulaz[pocetak:kraj]
            prozor_izlaz = izlaz[pocetak:kraj]

            klasa = np.bincount(prozor_izlaz).argmax()

            X.append(prozor_ulaz)
            y.append(klasa)

    return np.array(X), np.array(y)

ulaz, izlaz = napravi_sekvence(podaci, velicina_prozora, korak)

print('Oblik ulaza:', ulaz.shape)
print('Oblik izlaza:', izlaz.shape)

#

ulazTrening, ulazTest, izlazTrening, izlazTest = train_test_split(
    ulaz,
    izlaz,
    test_size=0.2,
    random_state=42,
    stratify=izlaz
)

ulazTrening, ulazVal, izlazTrening, izlazVal = train_test_split(
    ulazTrening,
    izlazTrening,
    train_size=0.8,
    random_state=42,
    stratify=izlazTrening
)

print('Trening skup:', ulazTrening.shape)
print('Validacioni skup:', ulazVal.shape)
print('Test skup:', ulazTest.shape)

tezine_klasa = compute_class_weight(
    class_weight='balanced',
    classes=np.unique(izlazTrening),
    y=izlazTrening
)

tezine_klasa = dict(enumerate(tezine_klasa))
print('Tezine klasa po nazivima:')
for i, tezina in tezine_klasa.items():
    print(f'{klase[i]}: {tezina:.3f}')

#

broj_obelezja = ulazTrening.shape[2]

scaler = StandardScaler().fit(ulazTrening.reshape(-1, broj_obelezja))

ulazTreningNorm = scaler.transform(ulazTrening.reshape(-1, broj_obelezja)).reshape(ulazTrening.shape)
ulazValNorm = scaler.transform(ulazVal.reshape(-1, broj_obelezja)).reshape(ulazVal.shape)
ulazTestNorm = scaler.transform(ulazTest.reshape(-1, broj_obelezja)).reshape(ulazTest.shape)

#

def napravi_model(velicina_prozora, broj_obelezja, broj_klasa):
    model = Sequential()

    model.add(Input((velicina_prozora, broj_obelezja)))

    model.add(Conv1D(filters=32, kernel_size=5, activation='relu', padding='same'))
    model.add(MaxPooling1D(pool_size=2))

    model.add(Conv1D(filters=64, kernel_size=5, activation='relu', padding='same'))
    model.add(MaxPooling1D(pool_size=2))

    model.add(LSTM(32))

    model.add(Dense(32, activation='relu'))
    model.add(Dropout(0.2))

    model.add(Dense(broj_klasa, activation='softmax'))

    model.compile(optimizer='adam',
                  loss='sparse_categorical_crossentropy',
                  metrics=['accuracy'])

    return model


model = napravi_model(velicina_prozora, broj_obelezja, broj_klasa)
model.summary()
#

es = EarlyStopping(monitor='val_accuracy',
                   patience=5,
                   restore_best_weights=True,
                   verbose=1)

istorija = model.fit(ulazTreningNorm,
                     izlazTrening,
                     epochs=30,
                     batch_size=64,
                     validation_data=(ulazValNorm, izlazVal),
                     callbacks=[es],
                     class_weight=tezine_klasa,
                     verbose=1)
#

plt.figure(figsize=(12, 5))

